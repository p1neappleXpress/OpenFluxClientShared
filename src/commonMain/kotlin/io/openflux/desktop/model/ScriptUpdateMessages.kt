package io.openflux.desktop.model

/** Words for the core's script-update codes (the core reports codes only). */
object ScriptUpdateMessages {
    fun failure(code: String): String = when (code) {
        "no_source" -> "У транспорта не указано, где искать обновления"
        "fetch_failed" -> "Не удалось получить сведения об обновлении: проверьте сеть"
        "insecure_url" -> "Адрес обновления не https, транспорт его не принимает"
        "bad_index" -> "Файл обновлений автора повреждён"
        "id_mismatch" -> "Обновление относится к другому транспорту"
        "no_channel" -> "У автора нет выпуска для этого канала"
        "needs_newer_app" -> "Обновлению нужна более новая версия приложения"
        "key_changed" -> "Автор сменил ключ подписи. Это не обновление: импортируйте транспорт заново и сверьте отпечаток"
        "wire_break" -> "Обновление меняет формат обмена: ноду тоже нужно обновить"
        "bad_hash" -> "Скачанный файл не совпадает с тем, что обещал автор"
        "bad_package" -> "Скачанный файл не читается как транспорт"
        "bad_signature" -> "Подпись не совпадает с ключом автора. Обновление отклонено"
        "version_mismatch" -> "Версия в скачанном файле не та, что объявлена"
        "not_newer" -> "В скачанном файле версия не новее установленной"
        "install_failed" -> "Не удалось записать обновление на диск"
        "no_previous" -> "Предыдущей версии нет"
        "unsupported" -> "Обновления транспортов здесь не поддерживаются"
        "gone" -> "Транспорт уже удалён"
        else -> "Не получилось: $code"
    }
}
